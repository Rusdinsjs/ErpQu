//! HR Domain Routes (Fase 1 - 7)

use axum::{
    routing::{delete, get, post, put},
    Router,
};

use crate::api::handlers::{
    hr_driver_p2h_safety_handler, hr_leaves_handler, hr_lifecycle_handler,
    hr_loans_claims_kpi_handler, hr_payroll_handler,
    hr_recruitment_training_discipline_handler, hr_shift_overtime_handler,
};
use crate::api::server::AppState;

pub fn hr_routes() -> Router<AppState> {
    Router::new()
        // HR Fase 1 - Employee Lifecycle & Organization
        .route(
            "/designations",
            get(hr_lifecycle_handler::list_designations)
                .post(hr_lifecycle_handler::create_designation),
        )
        .route(
            "/designations/:id",
            get(hr_lifecycle_handler::get_designation)
                .put(hr_lifecycle_handler::update_designation)
                .delete(hr_lifecycle_handler::delete_designation),
        )
        .route(
            "/employment-types",
            get(hr_lifecycle_handler::list_employment_types)
                .post(hr_lifecycle_handler::create_employment_type),
        )
        .route(
            "/lifecycle-events",
            get(hr_lifecycle_handler::list_lifecycle_events)
                .post(hr_lifecycle_handler::create_lifecycle_event),
        )
        .route(
            "/employees/:id/360",
            get(hr_lifecycle_handler::get_employee_360),
        )
        .route(
            "/employees/:id/documents",
            get(hr_lifecycle_handler::list_employee_documents)
                .post(hr_lifecycle_handler::create_employee_document),
        )
        .route(
            "/documents/:id",
            delete(hr_lifecycle_handler::delete_employee_document),
        )
        .route(
            "/employees/:id/education",
            get(hr_lifecycle_handler::list_employee_education)
                .post(hr_lifecycle_handler::create_employee_education),
        )
        .route(
            "/education/:id",
            delete(hr_lifecycle_handler::delete_employee_education),
        )

        // HR Fase 2 - Shift Management & Overtime
        .route(
            "/shift-types",
            get(hr_shift_overtime_handler::list_shift_types)
                .post(hr_shift_overtime_handler::create_shift_type),
        )
        .route(
            "/shift-types/:id",
            get(hr_shift_overtime_handler::get_shift_type)
                .put(hr_shift_overtime_handler::update_shift_type)
                .delete(hr_shift_overtime_handler::delete_shift_type),
        )
        .route(
            "/shift-assignments",
            get(hr_shift_overtime_handler::list_shift_assignments)
                .post(hr_shift_overtime_handler::create_shift_assignment),
        )
        .route(
            "/attendance-logs",
            get(hr_shift_overtime_handler::list_attendance_details),
        )
        .route(
            "/overtime-claims",
            get(hr_shift_overtime_handler::list_overtime_requests)
                .post(hr_shift_overtime_handler::create_overtime_request),
        )
        .route(
            "/overtime-claims/:id/review",
            post(hr_shift_overtime_handler::review_overtime_request),
        )
        .route(
            "/attendance-requests",
            get(hr_shift_overtime_handler::list_attendance_requests)
                .post(hr_shift_overtime_handler::create_attendance_request),
        )
        .route(
            "/attendance-requests/:id/review",
            post(hr_shift_overtime_handler::review_attendance_request),
        )

        // HR Fase 3 - Leaves & Holidays
        .route(
            "/leave-types",
            get(hr_leaves_handler::list_leave_types)
                .post(hr_leaves_handler::create_leave_type),
        )
        .route(
            "/leave-types/:id",
            get(hr_leaves_handler::get_leave_type)
                .put(hr_leaves_handler::update_leave_type)
                .delete(hr_leaves_handler::delete_leave_type),
        )
        .route(
            "/leave-allocations",
            get(hr_leaves_handler::list_allocations)
                .post(hr_leaves_handler::create_allocation),
        )
        .route(
            "/leave-allocations/bulk",
            post(hr_leaves_handler::bulk_allocate),
        )
        .route(
            "/employees/:id/leave-balance",
            get(hr_leaves_handler::get_leave_balance),
        )
        .route(
            "/leave-applications",
            get(hr_leaves_handler::list_applications)
                .post(hr_leaves_handler::create_application),
        )
        .route(
            "/leave-applications/:id",
            get(hr_leaves_handler::get_application),
        )
        .route(
            "/leave-applications/:id/review",
            post(hr_leaves_handler::review_application),
        )
        .route(
            "/holiday-lists",
            get(hr_leaves_handler::list_holiday_lists),
        )
        .route(
            "/holiday-lists/:id/holidays",
            get(hr_leaves_handler::list_holidays).post(hr_leaves_handler::add_holiday),
        )
        .route(
            "/leave-block-lists",
            get(hr_leaves_handler::list_block_lists),
        )
        .route(
            "/shifts",
            get(hr_shift_overtime_handler::list_shift_types)
                .post(hr_shift_overtime_handler::create_shift_type),
        )
        .route(
            "/shifts/:id",
            get(hr_shift_overtime_handler::get_shift_type)
                .put(hr_shift_overtime_handler::update_shift_type)
                .delete(hr_shift_overtime_handler::delete_shift_type),
        )
        .route(
            "/shift-assignments/bulk",
            post(hr_shift_overtime_handler::bulk_assign_shifts),
        )
        .route(
            "/shift-assignments/:id",
            delete(hr_shift_overtime_handler::delete_shift_assignment),
        )
        .route(
            "/overtime-requests",
            get(hr_shift_overtime_handler::list_overtime_requests)
                .post(hr_shift_overtime_handler::create_overtime_request),
        )
        .route(
            "/overtime-requests/:id/review",
            post(hr_shift_overtime_handler::review_overtime_request),
        )
        .route(
            "/attendance-recap",
            get(hr_shift_overtime_handler::get_attendance_recap),
        )

        // HR Fase 4 - Payroll
        .route(
            "/salary-components",
            get(hr_payroll_handler::list_salary_components)
                .post(hr_payroll_handler::create_salary_component),
        )
        .route(
            "/salary-components/:id",
            get(hr_payroll_handler::get_salary_component)
                .put(hr_payroll_handler::update_salary_component)
                .delete(hr_payroll_handler::delete_salary_component),
        )
        .route(
            "/salary-structures",
            get(hr_payroll_handler::list_salary_structures)
                .post(hr_payroll_handler::create_salary_structure),
        )
        .route(
            "/salary-structures/:id",
            get(hr_payroll_handler::get_salary_structure)
                .put(hr_payroll_handler::update_salary_structure)
                .delete(hr_payroll_handler::delete_salary_structure),
        )
        .route(
            "/salary-assignments",
            get(hr_payroll_handler::list_salary_assignments)
                .post(hr_payroll_handler::create_salary_assignment),
        )
        .route(
            "/payroll-entries",
            get(hr_payroll_handler::list_payroll_entries)
                .post(hr_payroll_handler::run_payroll_entry),
        )
        .route(
            "/salary-slips",
            get(hr_payroll_handler::list_salary_slips),
        )
        .route(
            "/salary-slips/:id",
            get(hr_payroll_handler::get_salary_slip),
        )

        // HR Fase 5 - Loans, Claims & KPI
        .route(
            "/loan-types",
            get(hr_loans_claims_kpi_handler::list_loan_types),
        )
        .route(
            "/employee-loans",
            get(hr_loans_claims_kpi_handler::list_employee_loans)
                .post(hr_loans_claims_kpi_handler::apply_loan),
        )
        .route(
            "/employee-loans/:id/review",
            post(hr_loans_claims_kpi_handler::review_loan),
        )
        .route(
            "/employee-loans/:id/schedules",
            get(hr_loans_claims_kpi_handler::list_repayment_schedules),
        )
        .route(
            "/expense-claim-types",
            get(hr_loans_claims_kpi_handler::list_expense_claim_types),
        )
        .route(
            "/expense-claims",
            get(hr_loans_claims_kpi_handler::list_expense_claims)
                .post(hr_loans_claims_kpi_handler::create_expense_claim),
        )
        .route(
            "/expense-claims/:id/review",
            post(hr_loans_claims_kpi_handler::review_expense_claim),
        )
        .route(
            "/appraisal-templates",
            get(hr_loans_claims_kpi_handler::list_appraisal_templates),
        )
        .route(
            "/appraisal-templates/:id/items",
            get(hr_loans_claims_kpi_handler::list_template_items),
        )
        .route(
            "/employee-appraisals",
            get(hr_loans_claims_kpi_handler::list_employee_appraisals)
                .post(hr_loans_claims_kpi_handler::submit_employee_appraisal),
        )

        // HR Fase 6 - Recruitment ATS, Training & Disciplinary Actions
        .route(
            "/job-openings",
            get(hr_recruitment_training_discipline_handler::list_job_openings)
                .post(hr_recruitment_training_discipline_handler::create_job_opening),
        )
        .route(
            "/job-applicants",
            get(hr_recruitment_training_discipline_handler::list_job_applicants)
                .post(hr_recruitment_training_discipline_handler::create_job_applicant),
        )
        .route(
            "/job-applicants/:id/stage",
            post(hr_recruitment_training_discipline_handler::update_applicant_stage),
        )
        .route(
            "/job-applicants/:id/convert-to-employee",
            post(hr_recruitment_training_discipline_handler::convert_applicant_to_employee),
        )
        .route(
            "/training-programs",
            get(hr_recruitment_training_discipline_handler::list_training_programs)
                .post(hr_recruitment_training_discipline_handler::create_training_program),
        )
        .route(
            "/training-events",
            get(hr_recruitment_training_discipline_handler::list_training_events)
                .post(hr_recruitment_training_discipline_handler::create_training_event),
        )
        .route(
            "/training-events/:id/participants",
            get(hr_recruitment_training_discipline_handler::list_training_participants)
                .post(hr_recruitment_training_discipline_handler::add_training_participant),
        )
        .route(
            "/employee-certifications",
            get(hr_recruitment_training_discipline_handler::list_employee_certifications)
                .post(hr_recruitment_training_discipline_handler::create_employee_certification),
        )
        .route(
            "/disciplinary-actions",
            get(hr_recruitment_training_discipline_handler::list_disciplinary_actions)
                .post(hr_recruitment_training_discipline_handler::issue_disciplinary_action),
        )

        // HR Fase 7 - Driver Ops, P2H & Safety Incidents
        .route(
            "/driver-assignments",
            get(hr_driver_p2h_safety_handler::list_driver_assignments)
                .post(hr_driver_p2h_safety_handler::create_driver_assignment),
        )
        .route(
            "/driver-assignments/:id/return",
            post(hr_driver_p2h_safety_handler::return_driver_assignment),
        )
        .route(
            "/p2h-inspections",
            get(hr_driver_p2h_safety_handler::list_p2h_inspections)
                .post(hr_driver_p2h_safety_handler::submit_p2h_inspection),
        )
        .route(
            "/driver-safety-incidents",
            get(hr_driver_p2h_safety_handler::list_driver_safety_incidents)
                .post(hr_driver_p2h_safety_handler::create_driver_safety_incident),
        )
        .route(
            "/vehicle-handovers",
            get(hr_driver_p2h_safety_handler::list_vehicle_handovers)
                .post(hr_driver_p2h_safety_handler::create_vehicle_handover),
        )
}
